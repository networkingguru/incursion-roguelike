#!/usr/bin/env bash
# gate: live
#
# Is a character walked through the real creation screens the same character
# as the one built from the .char file that walk recorded?
#
# WHAT IS BEING PROVED. Spec section 9, C2, amendments B1 (mutation e), B9, B17
# and B18 (bead inc-10v7f, phase 10; AC3). Each walk runs with the Live
# creation source recording (INCURSION_RECORD_CHAR). tools/build_fixture.sh
# builds the .char the walk wrote with the File source. tools/char_dump.sh dumps
# both saved characters (the walk side is <name>.walk.sav, the save the game
# writes at the end of game setup, before the walk's first turn), and tools/canon_compare.py compares the two dumps in
# both directions. The round trip is the one tools/compare_creation_walks.sh
# --build runs (round_trip in tools/creation_walks_lib.sh). When the builder
# skips a creation step, or creation gains a draw, a prompt or a raw-key screen
# that the .char does not state, a walk and its build differ, and this check
# fails and names the walk.
#
# Default mode, the gate subset: the walks listed in GATE_WALKS below, each
# ending at creation with a save. Every menu entry is chosen by name with
# @choose (B9). A grid that is not a menu (point buy, the skill ranks) uses
# cursor keys.
# --sweep, the nightly run: one walk per race-by-class pair, generated by
# tools/creation_walks_lib.sh from the game's own menus. A pair the game refuses
# is REFUSED, not a failure.
#
# Output, one line per walk:
#   SAME      the two dumps agree
#   DIFF      the dumps differ (the diff path follows)
#   BUILDFAIL the builder stopped (the BUILD FAILED line follows)
#   NOWALK    the walk saved no character or recorded no .char (exit code follows)
#   DUMPFAIL  a dump could not be made
#   REFUSED   (sweep only) the game refused the pair
# then the coverage result (gate mode only; the sweep prints one line saying so). Coverage: the decision keys are read at
# run time from CREATION_KEY_LIST in inc/CreationSource.h; this check holds no
# list of keys. A key a .char may state (its table default is not NULL, the
# test CreationKeyIsInput makes) is HIT when some walk of the run recorded it.
# The gate mode fails on any such key no walk hit, and names it. The sweep does not
# compute or judge coverage. A key the
# header marks NOT_REACHED (creation cannot reach it) is not demanded; it is
# listed on one line. Both modes FAIL, naming the key and the walk, when a
# walk's .char states a key flagged NOT_REACHED (a stale flag). A key with a NULL default is the screen choice whose
# result other keys already state; the recorder never writes it, so it cannot be hit this way and is listed apart.
#
# fact: the character -- walked by a key script that chooses its race, class and every menu entry by name with @choose, then built from the .char that walk recorded; the check compares the two dumps with each other and reads no value of either
# fact: the seed -- every walk and its build of one character must agree whatever the seed (inc-10v7f, spec B9); the .char carries seed: for the build, and the check proves the agreement by comparing the two dumps, so it reads no seed-specific value
# fact: the perks a rolled attribute set offers -- the paladin and Asherath priest walks take a rolled set whose perks the stream decides, to hit perk_immune, perk_spell and perk_ability, because a key script cannot choose a set by its perk (inc-10v7f); a stream change that moves those perks makes the coverage line name the key, and the walk and its build still agree
# fact: the settings -- each walk names its settings file (tools/fixtures/options-2026-08-22*.dat, committed), and the .char options: line carries it to the build
# fact: the race and class lists of --sweep -- read from the game's menus at run time by tools/creation_walks_lib.sh
# fact: the decision keys -- read from the CREATION_KEY_LIST X-macro in inc/CreationSource.h by sed at run time, so a new key is covered the moment it is added
#
# Usage: tools/check_fixture_equivalence.sh             (the gate subset)
#        tools/check_fixture_equivalence.sh --sweep     (every race by class pair)
#   INCURSION_NEW_BIN=<binary>  the binary under test (default ./incursion-headless)
#   C2_WALK_FILTER=<regex>      run only the walks whose name matches (gate or sweep;
#                               gate coverage is then not judged)
# Specimens: logs/c2/gate/ or logs/c2/sweep/.
# Exit: 0 every walk SAME (gate mode: and full coverage); 1 otherwise; 2 bad usage or no binary.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT" || exit 2

MODE=gate
case "${1:-}" in
    "") ;;
    --sweep) MODE=sweep ;;
    *) echo "usage: $0 [--sweep]" >&2; exit 2 ;;
esac
NEW="${INCURSION_NEW_BIN:-./incursion-headless}"
[ -x "$NEW" ] || { echo "$NEW is not built. Run: BACKEND=posix ./build_macos.sh" >&2; exit 2; }
HDR=inc/CreationSource.h
[ -f "$HDR" ] || { echo "$HDR is missing" >&2; exit 2; }

OUT="logs/c2/$MODE"
mkdir -p "$OUT/keys" "$OUT/runs"
O22=tools/fixtures/options-2026-08-22.dat
B17=tools/fixtures/options-2026-08-22-b17.dat
B17NH=tools/fixtures/options-2026-08-22-b17-noautohide.dat   # the sweep: no pair hides in the first turn of play
OPT=$O22   # the settings the menu-reading runs use

# shellcheck source=creation_walks_lib.sh
. "$ROOT/tools/creation_walks_lib.sh"

# run_keys <name> <keyfile> <options>: the lib's menu reading runs a key script
# in its own run directory; its screens are read afterwards.
run_keys() {
    INCURSION_OPTIONS="$3" INCURSION_BIN="$NEW" INCURSION_RUN_DIR="$ROOT/$OUT/runs/$1" \
        tools/headless.sh "$2" 1 > "$OUT/runs/$1.out" 2>&1 </dev/null
}

# The gate walks: name, key script, seed, settings file. Each ends at creation
# with a save and chooses its menu entries by name with @choose (B9). Each key
# script's header says what it walks and which keys it exists to hit. The first
# three run under B17 (rolled hit points and mana, random gender, Beginner's
# Kit). The paladin and the Asherath priest take a rolled attribute set whose
# perks the seed decides (see their headers): they hit perk_immune, perk_spell
# and perk_ability. The ranger runs with OPT_AUTOHIDE off: a ranger would hide
# in the first turn of play otherwise.
NH=tools/fixtures/options-2026-08-22-noautohide.dat
GATE_WALKS=(
  "orc-barbarian-b17        tools/keys/c2-orc-barbarian-b17.keys        1  $B17"
  "human-priest-multitude   tools/keys/c2-human-priest-multitude.keys   1  $B17"
  "human-mage-schoolfocus   tools/keys/c2-human-mage-schoolfocus.keys   1  $B17"
  "human-warrior-feats      tools/keys/c2-human-warrior-feats.keys      1  $O22"
  "drow-ranger              tools/keys/c2-drow-ranger.keys              1  $NH"
  "human-paladin-perks      tools/keys/c2-human-paladin.keys            4  $O22"
  "human-priest-asherath    tools/keys/c2-human-priest-asherath.keys    1  $O22"
  "human-priest-inherent    tools/keys/c2-human-priest-inherent.keys    1  $O22"
  "elf-monk-ring            tools/keys/c2-elf-monk.keys                 1  $B17NH"
)

# The creation tail of a walk that saves. The shared tail (tail_block) meets
# every screen but a ranger's two: the favoured enemy and the combat style.
sweep_tail() {   # sweep_tail [withlearn]
    local _
    for _ in 1 2 3 4 5; do
        tail_block
        echo '@while "favoured enemy" a'
        echo '@while "Combat style" t'
    done
    [ "${1:-}" = learn ] && learn_seq
    tail_block
}

fail=0
refused=0
same=0
n=0
sweep_walk() {   # sweep_walk <race> <class>
    local race="$1" class="$2" name keys
    name="pair-${race// /_}-${class// /_}"
    keys="$OUT/keys/$name.keys"
    { head_keys "$race" "$class"; sweep_tail; save_tail; } > "$keys"
    round_trip "$name" "$keys" 1 "$B17NH" "$OUT"
    local rc=$?
    if [ "$RT_KIND" = NOWALK ]; then
        # A caster is asked for starting spells: run again with the spell tail.
        if grep -q "Learn Spells: Level" "$OUT/$name-walk/logs/screens/"*.txt 2>/dev/null; then
            { head_keys "$race" "$class"; sweep_tail learn; save_tail; } > "$keys"
            round_trip "$name" "$keys" 1 "$B17NH" "$OUT"
            rc=$?
        fi
    fi
    if [ "$RT_KIND" = NOWALK ] && grep -q "do not meet the requirements\|Your class describes" \
            "$OUT/$name-walk/logs/screens/"*.txt 2>/dev/null; then
        echo "REFUSED  $name"; refused=$((refused + 1)); return 0
    fi
    return $rc
}

t0=$SECONDS
START="$OUT/.run-start"; : > "$START"   # a .char older than this belongs to an earlier run
if [ "$MODE" = sweep ]; then
    cw_read_menus || { echo "could not read the race and class menus"; exit 2; }
    while IFS= read -r race; do
        while IFS= read -r class; do
            if [ -n "${C2_WALK_FILTER:-}" ] && ! [[ "pair-${race// /_}-${class// /_}" =~ $C2_WALK_FILTER ]]; then continue; fi
            n=$((n + 1))
            sweep_walk "$race" "$class" && { [ "$RT_KIND" = SAME ] && same=$((same + 1)); } || { [ "$RT_KIND" = SAME ] || fail=1; }
        done <<<"$CLASSES"
    done <<<"$RACES"
else
    for row in "${GATE_WALKS[@]}"; do
        set -- $row
        name="$1"; keys="$2"; seed="$3"; opts="$4"
        if [ -n "${C2_WALK_FILTER:-}" ] && ! [[ "$name" =~ $C2_WALK_FILTER ]]; then continue; fi
        n=$((n + 1))
        if round_trip "$name" "$keys" "$seed" "$opts" "$OUT"; then same=$((same + 1)); else fail=1; fi
    done
fi
elapsed=$((SECONDS - t0))

# Coverage. The keys come from the enum; the hits come from the .char files the
# walks recorded.
KEYS_IN=$(sed -n 's/^[[:space:]]*X(\([A-Z0-9_]*\),[[:space:]]*[A-Z]*,[[:space:]]*\(.*\),[[:space:]]*\([A-Z_]*\))[[:space:]]*\\\{0,1\}$/\1 \3 \2/p' "$HDR")
[ -n "$KEYS_IN" ] || { echo "could not read the key list from $HDR"; exit 2; }
stale=0; missing=""; nkeys=0; nhit=0; apart=""; later=""
RAN=$(find "$OUT" -maxdepth 1 -name "*.char" -newer "$START" 2>/dev/null | sort)   # the walks that ran now
HITS=$(cat $RAN 2>/dev/null | grep -vE '^[[:space:]]*(#|$)' | sed -E 's/^([a-z0-9_]+)[ :].*/\1/' | sort -u)
while read -r key reach dflt; do
    lk=$(printf '%s' "$key" | tr 'A-Z' 'a-z')
    if [ "$dflt" = NULL ]; then apart="$apart $lk"; continue; fi
    if [ "$reach" = NOT_REACHED ]; then
        later="$later $lk"
        # A walk that states a key the header calls unreachable proves the flag stale.
        if grep -qx "$lk" <<<"$HITS"; then
            for cf in $(grep -lE "^$lk[ :]" $RAN); do
                echo "STALE FLAG: key $lk is marked NOT_REACHED in $HDR but walk $(basename "$cf" .char) states it"
            done
            stale=1
        fi
        continue
    fi
    [ "$MODE" = sweep ] && continue   # the sweep judges no coverage
    nkeys=$((nkeys + 1))
    if grep -qx "$lk" <<<"$HITS"; then nhit=$((nhit + 1)); else missing="$missing $lk"; fi
done <<<"$KEYS_IN"

echo "walks: $n  same: $same  refused: $refused  wall: ${elapsed}s"
if [ "$MODE" = sweep ]; then
    echo "coverage is judged by the gate mode only; the sweep does not compute it"
elif [ -n "${C2_WALK_FILTER:-}" ]; then
    echo "COVERAGE not judged (C2_WALK_FILTER is set)"
elif [ -z "$missing" ]; then
    echo "COVERAGE ok: $nhit of $nkeys keys hit"
else
    for k in $missing; do echo "COVERAGE MISS: key $k was hit by no walk"; done
    fail=1
fi
[ $stale -eq 1 ] && fail=1
[ -n "$apart" ] && echo "not stated in a .char (NULL default; the recorder never writes them):$apart"
[ -n "$later" ] && echo "not demanded (creation cannot reach them; the header marks them NOT_REACHED):$later"
[ "$n" -gt 0 ] || { echo "no walk ran"; exit 1; }
[ $fail -eq 0 ] && echo "PASS" && exit 0
echo "FAIL"
exit 1
