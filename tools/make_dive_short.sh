#!/bin/bash
#
# inc-tre9h: write tools/keys/dive-depth-{2..10}.keys, one session per depth.
#
#   tools/make_dive_short.sh
#
# A key script has no parameter, so one file per depth comes from here. Each
# session makes a character, jumps once to depth d with the wizard command (DUN_DEPTH
# is 10, lib/dungeon.irh:17, so every jump is accepted), wakes every creature, waits
# 20 times, searches once ("s", as dive.keys does, so the session reaches
# Creature::Search, ExtendedAction and HaltAction) and waits 2 more. The "." after
# the jump clears the jump's message so the next "w" opens the menu. It replaces the
# one-session dive-short.keys (inc-b0ziu.2), which a death at depth 3 kept from ever
# reaching depth 10.
#
# The script answers NO prompt. It presses past the two routine message pauses,
# "#------" and "Press [ENTER] to continue", and nothing else. Before every key
# that needs the map, @maponly ends the session if the game is waiting anywhere
# else (@menuopen does the same after the "w" that opens the wizard menu): a death
# prompt, a paralysis prompt, a search prompt. The stop is a counted result
# (logs/prompt-stop.log names the depth and the prompt), not a lost-sync exit 6.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

pauses() {
    echo '@while "Press [ENTER] to continue" ENTER'
    echo '@while "#------" SPACE'
}

for d in 2 3 4 5 6 7 8 9 10; do
    {
        echo "# GENERATED by tools/make_dive_short.sh -- do not edit by hand."
        echo "# One session at depth $d only: jump, wake every creature, 20 waits, s, 2 waits."
        echo "# Answers no prompt: @maponly ends the session at the first one (inc-tre9h)."
        echo
        echo "@include chargen.keys"
        echo
        echo "@dump:arrival"
        pauses
        echo "@maponly"
        echo "w y p \"$d\" ENTER"
        echo "@dump:depth$d"
        echo "."
        pauses
        echo "@maponly"
        echo "w"
        echo '@menuopen "Wizard Mode Options"'
        echo '@choose "Wake Every Creature"'
        for ((i = 0; i < 20; i++)); do
            pauses
            echo "@maponly"
            echo "."
        done
        pauses
        echo "@maponly"
        echo "s"
        for i in 1 2; do
            pauses
            echo "@maponly"
            echo "."
        done
        pauses
        echo "@maponly"
        echo "@dump:final"
        echo "@quit"
    } > "tools/keys/dive-depth-$d.keys"
done
