#!/bin/bash
# inc-b0ziu.2: write tools/keys/dive-short-{2,5,10,20}.keys, one wait count each.
#
#   tools/make_dive_short.sh
#
# A key script has no parameter, so one file per wait count comes from here.
# Each session jumps once to each depth 2..10 (DUN_DEPTH is 10, lib/dungeon.irh:17,
# so every jump is accepted), wakes every creature with the wizard command added
# in inc-b0ziu.2, and waits. The "." after each jump clears the jump's message so the
# next "w" opens the menu; the @while lines answer a fall or death prompt a wait caused. tools/keys/dive-short.keys is the 20-wait file.
# Each level ends ".*N s .*2": the "s" (search) mirrors dive.keys, which ends every level the same way;
# without it the session never reaches Creature::Search, ExtendedAction or HaltAction.
# The "1 w" body of the @until answers a paralysis prompt ("Pray, magic or wait") that a woken creature can raise while the loop runs; "w" alone cannot answer it.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

for waits in 2 5 10 20; do
    out="tools/keys/dive-short-$waits.keys"
    {
        echo "# GENERATED by tools/make_dive_short.sh -- do not edit by hand."
        echo "# One wizard jump to each depth 2..10, wake every creature, $waits waits."
        echo "# Short counterpart of dive.keys (inc-b0ziu.2). Needs OPT_NODEATH settings,"
        echo "# as dive.keys does, for the @while death-prompt lines."
        echo
        echo "@include chargen.keys"
        echo
        echo "@dump:arrival"
        echo
        for d in 2 3 4 5 6 7 8 9 10; do
            echo '@while "Press [ENTER] to continue" ENTER'
            echo '@while "#------" SPACE'
            echo '@while "Pray, magic or wait" 1'
            echo '@while "You die... Die?" n'
            echo '@while "Do you want to stop searching" y'
            if [ "$d" = 2 ]; then echo "w y p \"2\" ENTER"; else echo "w p \"$d\" ENTER"; fi
            if [ "$d" = 6 ] || [ "$d" = 10 ]; then echo "@dump:depth$d"; fi
            echo "."
            echo '@while "Press [ENTER] to continue" ENTER'
            echo '@while "#------" SPACE'
            echo '@while "You die... Die?" n'
            echo '@while "Pray, magic or wait" 1'
            echo '@while "Do you want to stop searching" y'
            echo '@until "Wizard Mode Options" 1 w'
            echo '@choose "Wake Every Creature"'
            echo ".*$waits s .*2"
        done
        echo
        echo '@while "#------" SPACE'
        echo "@dump:final"
        echo "@quit"
    } > "$out"
done
cp tools/keys/dive-short-20.keys tools/keys/dive-short.keys
