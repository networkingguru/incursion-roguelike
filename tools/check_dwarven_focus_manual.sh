#!/bin/bash
# gate: live
# inc-8p2j: manual Dwarven Focus reverses the worthy-foe CR comparison.
# fact: dwarf, level/CR 1, unused focus, starting map and position -- frozen dwarf-barbarian-focus.sav
# fact: no other living targets -- wizard Genocide Everything before summoning
# fact: adjacent named target -- wizard Monster Summoning, one square east
# fact: higher ogre CR 2, equal hobgoblin CR 1, lower goblin effective CR 0 -- named summons; live debug CR dumps asserted
# fact: target stays adjacent, no combat/AI outcome read -- wizard Freeze Monsters before summoning
# fact: Auto-Focus off -- options-dwarven-focus.dat byte OPT_DWARVEN_AUTOFOCUS (214) = 0, also used to freeze character
# fact: manual ability and target selected -- guarded Dwarven Focus menu choice, east target, target-prompt dump
# fact: acceptance/refusal text -- fixed manual-command strings in src/Skills.cpp, isolated focus-result dump
# Options provenance: options-2026-08-22.dat with only byte 214 set to zero.
# Goblin's resource CR is negative under these settings; ChallengeRating() floors it to 0.
# No rolls, monster gear, HP, names generated by the seed, or AI choices are asserted.
# Exit 0: all ACs pass; 1: measured behavior/CR assertion fails; 2: could not measure.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT" || exit 2
OPTIONS="$ROOT/tools/fixtures/options-dwarven-focus.dat"
FIXTURE="$ROOT/tools/fixtures/chars/dwarf-barbarian-focus.sav"
[ -x ./incursion-headless ] && [ -f "$FIXTURE" ] || {
    echo 'INCONCLUSIVE: build with BACKEND=posix ./build_macos.sh; frozen dwarf required'
    exit 2
}
python3 - "$OPTIONS" <<'PY' || exit 2
import pathlib, sys
b = pathlib.Path(sys.argv[1]).read_bytes()
if len(b) != 900 or b[214] != 0:
    sys.exit('INCONCLUSIVE: named options must disable OPT_DWARVEN_AUTOFOCUS (214)')
PY
mkdir -p "$ROOT/logs/dwarven-focus"
OUT=$(mktemp -d "$ROOT/logs/dwarven-focus/check-XXXXXX") || exit 2
echo "specimens: $OUT"
for case in higher equal lower; do
    INCURSION_OPTIONS="$OPTIONS" INCURSION_LOAD="$FIXTURE" \
    INCURSION_RUN_DIR="$OUT/$case" tools/headless.sh \
        "tools/keys/dwarven-focus-$case.keys" 1 > "$OUT/$case.log" 2>&1
    status=$?
    if [ "$status" -ne 0 ] && [ "$status" -ne 3 ]; then
        echo "INCONCLUSIVE: $case harness exited $status; see $OUT/$case.log"
        exit 2
    fi
    if ! grep -q '^death: *none$' "$OUT/$case.log" || \
       ! grep -q '^stuck-prompt: none$' "$OUT/$case.log" || \
       grep -q 'gave up after' "$OUT/$case.log"; then
        echo "INCONCLUSIVE: $case setup did not complete; see $OUT/$case.log"
        exit 2
    fi
done
python3 - "$OUT" <<'PY'
from pathlib import Path
import re
import sys
root = Path(sys.argv[1])
failed = False
def inconclusive(message):
    print(f'INCONCLUSIVE: {message}')
    sys.exit(2)

for ac, case, monster, expected_cr, accepted in [
    ('AC-a', 'higher', 'ogre', 2, True),
    ('AC-b', 'equal', 'hobgoblin', 1, True),
    ('AC-c', 'lower', 'goblin', 0, False),
]:
    def screen(label):
        files = list((root / case / 'logs/screens').glob(f'*-{label}.txt'))
        if len(files) != 1:
            inconclusive(f'{case}: missing/ambiguous {label} screen')
        # Discard sidebar: it lists the target even while inspecting other objects.
        return '\n'.join(line.split('|')[0] for line in files[0].read_text().splitlines()[1:])
    player, target = screen('player-cr'), screen('target-cr')
    prompt, result = screen('target-prompt'), screen('focus-result')
    own = re.search(r'\bCR:(-?\d+)\b', player)
    foe = re.search(r'\bCR:(-?\d+)\b', target)
    if not (own and foe and 'dwarf named ' in player
            and f': {monster} (class T_MONSTER,' in target
            and 'Choose your target:' in prompt and monster in prompt):
        inconclusive(f'{case}: character/target/CR/manual selection evidence missing')
    own, foe = int(own[1]), int(foe[1])
    if own != 1 or foe != expected_cr:
        print(f'FAIL {ac}: CR setup changed: dwarf={own}, {monster}={foe}; expected 1/{expected_cr}')
        failed = True
        continue
    vow = f'You swear a vow to slay the {monster}.'
    refusal = "That's hardly a worthy foe for you!"
    want, reject = (vow, refusal) if accepted else (refusal, vow)
    passed = want in result and reject not in result
    observed = next((line.strip() for line in result.splitlines()
                     if vow in line or refusal in line), '(no vow or refusal printed)')
    print(f'{"PASS" if passed else "FAIL"} {ac}: dwarf CR {own}, {monster} CR {foe}: {observed}')
    failed |= not passed
sys.exit(1 if failed else 0)
PY
