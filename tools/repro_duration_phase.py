#!/usr/bin/env python3
"""One-off measurement, not a gate/check. Usage: python3 tools/repro_duration_phase.py DELAY [ROLL] [SPELL]
Pinned seed 5, fixture/options as in check_heal_maladies; no monster freeze.
Uncontrolled: AI decisions, attack rolls, target readiness, attainable cast phase.
"""
import os, pathlib, shutil, subprocess, sys
root=pathlib.Path(__file__).resolve().parent.parent
os.chdir(root)
delay=int(sys.argv[1]); roll=sys.argv[2] if len(sys.argv)>2 else '1'
spell=sys.argv[3] if len(sys.argv)>3 else 'Hold Person'
base=root/'logs/duration-phase'; base.mkdir(exist_ok=True)
scratch=base/'scratch'
if not scratch.exists():
    scratch.mkdir(); (scratch/'mod').mkdir(); (scratch/'logs').mkdir(); (scratch/'save').mkdir()
    shutil.copytree(root/'lib',scratch/'lib'); (scratch/'inc').symlink_to(root/'inc')
    with (scratch/'lib/main.irc').open('a') as f: f.write((root/'tools/fixtures/heal-maladies-god.irh').read_text())
    with (scratch/'compile.log').open('w') as f:
        subprocess.run(['./incursion-headless','-compile','main.irc'],env={**os.environ,'INCURSIONPATH':str(scratch)+'/'},stdin=subprocess.DEVNULL,stdout=f,stderr=f,check=True)
name=f'{spell.lower().replace(" ","-")}-d{delay}-r{roll}'
run=base/(name+'-measured')
serial=1
while run.exists():
    run=base/(name+f'-measured-{serial}'); serial+=1
run.mkdir()
for directory in ['lib','mod']:
    if not (run/directory).exists(): shutil.copytree(scratch/directory,run/directory)
keys=root/f'tools/repro_duration_phase_{name}.keys'
text='''SPACE
w
y
@choose "Genocide Everything"
SPACE*40
DELAY
w
@choose "Monster Summoning"
@choose "Kobolds"
@choose "kobold"
RIGHT
ENTER
w
@choose "Learn Any Spell"
"SPELL" ENTER
'''.replace('SPELL',spell)
text=text.replace('DELAY', ''.join('.\n@dump:delay-%d\n@while "more --" SPACE\n'%i for i in range(delay)))
text+='@dump:before-cast\nm\n@choose "'+spell+'"\nRIGHT\n@dump:target\nENTER\n@dump:after-cast\n@while "more --" SPACE\n'
text+=''.join('.\n@dump:after-wait-%d\n@while "more --" SPACE\n'%i for i in range(4))+'@quit\n'
if roll == 'none':
    text=text.replace('m\n@choose "'+spell+'"\nRIGHT\n@dump:target\nENTER', '@dump:target\n.')
if roll not in ('none',):
    inspect='w\n@choose "Examine Nearby Things"\nRIGHT\nDOWN*10\n@dump:status\nESC\n'
    text=text.replace('@dump:after-cast\n@while "more --" SPACE\n', '@dump:after-cast\n@while "more --" SPACE\n'+inspect)
keys.write_text('# Generated by tools/repro_duration_phase.py; one-off measurement.\n'+text)
env={**os.environ,'INCURSION_FORCE_SAVE_ROLL':('1' if roll=='none' else roll),'INCURSION_OPTIONS':'tools/fixtures/options-2026-08-22.dat','INCURSION_LOAD':'orc-barbarian-seed1-opt0822','INCURSION_RUN_DIR':str(run),'INCURSION_FIXTURE_CACHE':str(base/'fixture-cache')}
with (run/'runner.log').open('w') as f: result=subprocess.run(['tools/headless.sh',str(keys),'5'],env=env,stdout=f,stderr=f)
print(name,result.returncode)
for p in sorted((run/'logs/screens').glob('*.txt')):
    lines=p.read_text().splitlines(); print(p.name, '\n'.join(lines[:5]))
