#!/bin/bash
# gate: live
# Does a dungeon special ever land on top of another one? (inc-ydmt)
#
# Usage: tools/check_special_room_overlap.sh [seed ...]     # default seeds 1..40
#
# Exit: 0 PASS         -- at least one depth-2 generation logged both rooms,
#                         and no pair of rooms overlapped
#       1 FAIL         -- a depth-2 Parthenion rectangle overlaps the Ancient
#                         Library rectangle
#       2 UNMEASURED   -- no seed reached depth 2 with both rooms logged
#
# Dungeon level 2 has two specials (lib/dungeon.irh:19-24). The Library has no
# Grid, so Map::Generate (src/MakeLev.cpp, AN_DUNSPEC loop) puts it on a random
# panel not in PanelsDrawn. The Parthenion has a 27x22 Grid, and its placement
# never consults PanelsDrawn, so WriteMap can overwrite the Library.
# INCURSION_SPECIAL_PROBE=1 makes Map::Generate log each placed special to
# logs/special.log; this script runs one depth-2 session per seed
# (tools/keys/special-room-depth2.keys) and compares the two rectangles. A level
# regenerated by Game::GetDungeonMap logs again; every generation is judged.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

SEEDS=("$@")
[ ${#SEEDS[@]} -eq 0 ] && SEEDS=($(seq 1 40))

[ -x ./incursion-headless ] || {
    echo "UNMEASURED: ./incursion-headless not built. Run: BACKEND=posix ./build_macos.sh"
    exit 2
}

WORK="$ROOT/logs/special-room-overlap/$(date +%Y%m%d-%H%M%S)-$$"
mkdir -p "$WORK"
echo "seeds: ${#SEEDS[@]} (${SEEDS[0]}..${SEEDS[${#SEEDS[@]}-1]})"
echo "into:  $WORK"

run=0; measured=0; overlaps=0
for seed in "${SEEDS[@]}"; do
    RUNDIR="$WORK/seed-$seed"
    run=$((run + 1))
    INCURSION_SPECIAL_PROBE=1 \
    INCURSION_OPTIONS=tools/fixtures/options-2026-08-22.dat \
    INCURSION_RUN_DIR="$RUNDIR" \
        tools/headless.sh tools/keys/special-room-depth2.keys "$seed" > "$RUNDIR.out" 2>&1
    LOG="$RUNDIR/logs/special.log"
    [ -f "$LOG" ] || { echo "seed $seed: no special.log (session output: $RUNDIR.out)"; continue; }
    # One verdict line per generation of depth 2, then the overlap lines.
    awk -v seed="$seed" '
    function val(k,   m) { match($0, k "=[-0-9]+"); return substr($0, RSTART + length(k) + 1, RLENGTH - length(k) - 1) + 0 }
    /^SPECIAL depth=2 name="Ancient Library"/ { lx1=val("x1"); ly1=val("y1"); lx2=val("x2"); ly2=val("y2"); haveL=1; next }
    /^SPECIAL depth=2 name="Parthenion"/ {
        if (!haveL) next
        px1=val("x1"); py1=val("y1"); px2=val("x2"); py2=val("y2")
        ov = (px1 <= lx2 && lx1 <= px2 && py1 <= ly2 && ly1 <= py2)
        printf "PAIR %d %s library=(%d,%d)-(%d,%d) parthenion=(%d,%d)-(%d,%d)\n", seed, ov ? "OVERLAP" : "ok", lx1, ly1, lx2, ly2, px1, py1, px2, py2
        haveL=0
    }' "$LOG" > "$RUNDIR/pairs.txt"
    pairs="$(wc -l < "$RUNDIR/pairs.txt" | tr -d ' ')"
    [ "$pairs" -gt 0 ] || continue
    measured=$((measured + 1))
    ov="$(grep -c ' OVERLAP ' "$RUNDIR/pairs.txt" || true)"
    if [ "$ov" -gt 0 ]; then
        overlaps=$((overlaps + 1))
        grep ' OVERLAP ' "$RUNDIR/pairs.txt" | sed 's/^/  /'
    fi
done

echo
echo "seeds run: $run; seeds reaching depth 2 with both rooms logged: $measured; seeds with overlap: $overlaps"
if [ "$measured" -eq 0 ]; then
    echo "UNMEASURED: no seed logged both depth-2 rooms. This run proves nothing."
    exit 2
fi
if [ "$overlaps" -gt 0 ]; then
    echo "FAIL: the Parthenion overlaps the Ancient Library on $overlaps of $measured seeds."
    exit 1
fi
echo "PASS: no overlap on $measured seeds."
exit 0
